using System.Globalization;
using System.Text;
using Infrastructure.Data.Fashion;
using Microsoft.EntityFrameworkCore;

namespace FashionChatSeed;

public sealed record SeedColor(string Name, string Hex);
public sealed record SeedCategory(string Name, string Description, string Image, string Key);
public sealed record SeedRow(string Size, string? Chest, string? Waist, string? Hip);
public sealed record SeedChart(string Key, string Name, string Instructions, List<SeedRow> Rows);
public sealed record SeedProduct(string Code, string Name, string Category, string Chart, string Audience, decimal Price, decimal? OldPrice,
    string Material, string Fit, string Description, string Care, List<SeedColor> Colors, int Stock);
public sealed record SeedManifest(List<SeedCategory> Categories, List<SeedChart> Charts, List<SeedProduct> Products);
public sealed record ExportMedia(string Url, string PublicId, string? Alt, DateTime CreatedAt);
public sealed record ExportCategory(string Name, string? Description, string? ImagePublicId, int SortOrder, bool IsVisible);
public sealed record ExportRow(string Size, string? Chest, string? Waist, string? Hip, int SortOrder);
public sealed record ExportChart(string Name, string? Instructions, List<ExportRow> Rows);
public sealed record ExportVariant(string Sku, string Color, string Hex, string Size, int Stock, bool IsActive);
public sealed record ExportImage(string PublicId, int SortOrder, bool IsPrimary);
public sealed record ExportProduct(string Code, string Name, string? Brand, string CategoryName, string Audience, decimal Price, decimal? OldPrice,
    string Description, string? Material, string? Fit, string? Care, bool IsNew, bool Featured, bool IsVisible, string? ChartName,
    DateTime CreatedAt, DateTime UpdatedAt, List<ExportVariant> Variants, List<ExportImage> Images);
public sealed record CatalogBundle(List<ExportCategory> Categories, List<ExportChart> Charts, List<ExportMedia> Media, List<ExportProduct> Products);

public static class CatalogExport
{
    private static string S(string? value) => value is null ? "NULL" : "N'" + value.Replace("'", "''") + "'";
    private static string D(decimal? value) => value?.ToString(CultureInfo.InvariantCulture) ?? "NULL";
    private static string B(bool value) => value ? "1" : "0";
    private static string T(DateTime value) => "CONVERT(datetime2," + S(value.ToString("yyyy-MM-ddTHH:mm:ss.fffffff", CultureInfo.InvariantCulture)) + ",126)";

    public static string Build(CatalogBundle bundle)
    {
        var sql = new StringBuilder("""
            -- XMODE fashion chatbot acceptance catalog, exported 2026-11-10.
            -- Apply to a database already initialized with FashionContext migrations.
            -- Contains only the ten added products and their category/size/media dependencies.
            -- Identity IDs are resolved by natural keys. Rowversion values are generated by SQL Server.
            -- INSERT ONLY: repeat execution never resets existing stock or overwrites catalog edits.
            -- No accounts, orders, carts, API keys or connection strings are exported.
            SET NOCOUNT ON;
            SET XACT_ABORT ON;
            BEGIN TRY
            BEGIN TRANSACTION;
            IF OBJECT_ID(N'dbo.Products',N'U') IS NULL OR COL_LENGTH(N'dbo.Categories',N'IsDeleted') IS NULL
                THROW 51000, N'Initialize the current FashionContext schema before seeding.', 1;
            DECLARE @category int, @chart int, @product int, @media int;
            
            """);
        foreach (var media in bundle.Media)
            sql.AppendLine($"IF NOT EXISTS (SELECT 1 FROM dbo.MediaAssets WHERE PublicId={S(media.PublicId)})\nINSERT dbo.MediaAssets (Url,PublicId,Alt,CreatedAt) VALUES ({S(media.Url)},{S(media.PublicId)},{S(media.Alt)},{T(media.CreatedAt)});");
        foreach (var c in bundle.Categories)
        {
            var image = c.ImagePublicId is null ? "NULL" : $"(SELECT Id FROM dbo.MediaAssets WHERE PublicId={S(c.ImagePublicId)})";
            sql.AppendLine($"IF NOT EXISTS (SELECT 1 FROM dbo.Categories WHERE Name={S(c.Name)} AND IsDeleted=0)\nINSERT dbo.Categories (Name,Description,ImageId,SortOrder,IsVisible,IsDeleted) VALUES ({S(c.Name)},{S(c.Description)},{image},{c.SortOrder},{B(c.IsVisible)},0);");
        }
        foreach (var chart in bundle.Charts)
        {
            sql.AppendLine($"IF (SELECT COUNT(*) FROM dbo.SizeCharts WHERE Name={S(chart.Name)})>1 THROW 51001,N'Duplicate size chart name; resolve before seeding.',1;");
            sql.AppendLine($"IF NOT EXISTS (SELECT 1 FROM dbo.SizeCharts WHERE Name={S(chart.Name)})\nBEGIN\nINSERT dbo.SizeCharts (Name,Instructions) VALUES ({S(chart.Name)},{S(chart.Instructions)});\nSET @chart=CONVERT(int,SCOPE_IDENTITY());");
            foreach (var row in chart.Rows)
                sql.AppendLine($"INSERT dbo.SizeChartRows (SizeChartId,Size,Chest,Waist,Hip,SortOrder) VALUES (@chart,{S(row.Size)},{S(row.Chest)},{S(row.Waist)},{S(row.Hip)},{row.SortOrder});");
            sql.AppendLine("END;");
        }
        foreach (var p in bundle.Products)
        {
            sql.AppendLine($"IF EXISTS (SELECT 1 FROM dbo.Products WHERE Code={S(p.Code)} AND IsDeleted=1) THROW 51002,N'A seed product was deleted; it will not be restored automatically.',1;");
            sql.AppendLine($"IF NOT EXISTS (SELECT 1 FROM dbo.Products WHERE Code={S(p.Code)})\nBEGIN\nSELECT @category=Id FROM dbo.Categories WHERE Name={S(p.CategoryName)} AND IsDeleted=0;");
            sql.AppendLine(p.ChartName is null ? "SET @chart=NULL;" : $"SELECT @chart=Id FROM dbo.SizeCharts WHERE Name={S(p.ChartName)};");
            sql.AppendLine($"INSERT dbo.Products (Code,Name,Brand,CategoryId,Audience,Price,OldPrice,Description,Material,Fit,Care,IsNew,Featured,IsVisible,IsDeleted,SizeChartId,CreatedAt,UpdatedAt) VALUES ({S(p.Code)},{S(p.Name)},{S(p.Brand)},@category,{S(p.Audience)},{D(p.Price)},{D(p.OldPrice)},{S(p.Description)},{S(p.Material)},{S(p.Fit)},{S(p.Care)},{B(p.IsNew)},{B(p.Featured)},{B(p.IsVisible)},0,@chart,{T(p.CreatedAt)},{T(p.UpdatedAt)});\nSET @product=CONVERT(int,SCOPE_IDENTITY());");
            foreach (var v in p.Variants)
                sql.AppendLine($"INSERT dbo.ProductVariants (ProductId,Sku,Color,Hex,Size,Stock,IsActive) VALUES (@product,{S(v.Sku)},{S(v.Color)},{S(v.Hex)},{S(v.Size)},{v.Stock},{B(v.IsActive)});");
            foreach (var image in p.Images)
                sql.AppendLine($"SELECT @media=Id FROM dbo.MediaAssets WHERE PublicId={S(image.PublicId)};\nINSERT dbo.ProductImages (ProductId,MediaAssetId,SortOrder,IsPrimary) VALUES (@product,@media,{image.SortOrder},{B(image.IsPrimary)});");
            sql.AppendLine("END;");
        }
        sql.AppendLine("COMMIT TRANSACTION;\nEND TRY\nBEGIN CATCH\nIF @@TRANCOUNT>0 ROLLBACK TRANSACTION;\nTHROW;\nEND CATCH;");
        return sql.ToString();
    }

    public static async Task<CatalogBundle> ReadAsync(FashionContext db, string[] codes)
    {
        var products = await db.Products.AsNoTracking().Where(p => codes.Contains(p.Code)).Include(p => p.Category).ThenInclude(c => c.Image)
            .Include(p => p.Variants).Include(p => p.Images).ThenInclude(i => i.MediaAsset)
            .Include(p => p.SizeChart).ThenInclude(c => c!.Rows).AsSplitQuery().ToListAsync();
        if (products.Count != codes.Length || products.Any(p => p.IsDeleted)) throw new InvalidOperationException("Seed product set is incomplete or contains deleted products.");
        var categories = products.Select(p => p.Category).DistinctBy(c => c.Id).ToList();
        var charts = products.Where(p => p.SizeChart != null).Select(p => p.SizeChart!).DistinctBy(c => c.Id).ToList();
        var media = products.SelectMany(p => p.Images.Select(i => i.MediaAsset))
            .Concat(categories.Where(c => c.Image != null).Select(c => c.Image!)).DistinctBy(m => m.Id).ToList();
        return new(
            categories.Select(c => new ExportCategory(c.Name, c.Description, c.Image?.PublicId, c.SortOrder, c.IsVisible)).ToList(),
            charts.Select(c => new ExportChart(c.Name, c.Instructions, c.Rows.OrderBy(r => r.SortOrder).Select(r => new ExportRow(r.Size,r.Chest,r.Waist,r.Hip,r.SortOrder)).ToList())).ToList(),
            media.Select(m => new ExportMedia(m.Url,m.PublicId,m.Alt,m.CreatedAt)).ToList(),
            products.OrderBy(p => p.Code).Select(p => new ExportProduct(p.Code,p.Name,p.Brand,p.Category.Name,p.Audience,p.Price,p.OldPrice,
                p.Description,p.Material,p.Fit,p.Care,p.IsNew,p.Featured,p.IsVisible,p.SizeChart?.Name,p.CreatedAt,p.UpdatedAt,
                p.Variants.OrderBy(v => v.Sku).Select(v => new ExportVariant(v.Sku,v.Color,v.Hex,v.Size,v.Stock,v.IsActive)).ToList(),
                p.Images.OrderBy(i => i.SortOrder).Select(i => new ExportImage(i.MediaAsset.PublicId,i.SortOrder,i.IsPrimary)).ToList())).ToList());
    }
}
